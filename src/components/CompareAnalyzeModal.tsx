import React, { useState } from 'react';
import {
  X,
  Sparkles,
  CheckCircle2,
  AlertTriangle,
  Lightbulb,
  Award,
  Layers,
  ArrowRight,
  ShieldAlert,
  Download,
  Copy,
  Check,
} from 'lucide-react';
import { AnalysisResult, ProviderId, ModelResponse } from '../types';
import { PROVIDERS_CONFIG } from '../constants/providers';

interface CompareAnalyzeModalProps {
  isOpen: boolean;
  onClose: () => void;
  prompt: string;
  responses: Record<ProviderId, ModelResponse>;
  analysis: AnalysisResult | null;
  isLoading: boolean;
  onRunAnalysis: () => void;
}

export const CompareAnalyzeModal: React.FC<CompareAnalyzeModalProps> = ({
  isOpen,
  onClose,
  prompt,
  responses,
  analysis,
  isLoading,
  onRunAnalysis,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const handleCopyReport = () => {
    if (!analysis) return;
    const reportText = `OMNIA AI COMPARISON ANALYSIS REPORT
Prompt: ${prompt}
Evaluated By: ${analysis.evaluatedByModel} at ${analysis.evaluatedAt}

EXECUTIVE SUMMARY:
${analysis.executiveSummary}

POINTS OF AGREEMENT:
${analysis.agreements.map((a) => `- ${a}`).join('\n')}

POINTS OF DIVERGENCE:
${analysis.disagreements.map((d) => `- ${d}`).join('\n')}

BEST EXPLANATION:
${analysis.bestExplanation.provider.toUpperCase()}: ${analysis.bestExplanation.rationale}

BEST TECHNICAL RESPONSE:
${analysis.bestTechnical.provider.toUpperCase()}: ${analysis.bestTechnical.rationale}

STRONGEST REASONING:
${analysis.strongestReasoning.provider.toUpperCase()}: ${analysis.strongestReasoning.rationale}
`;
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-fade-in">
      <div className="relative w-full max-w-4xl max-h-[90vh] bg-neutral-950 border border-neutral-800 rounded-2xl shadow-2xl flex flex-col overflow-hidden">
        {/* Modal Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-neutral-800 bg-neutral-900/80">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-gradient-to-tr from-amber-500 via-rose-500 to-cyan-500 p-[1.5px] flex items-center justify-center">
              <div className="w-full h-full bg-neutral-950 rounded-[6px] flex items-center justify-center">
                <Sparkles className="w-4 h-4 text-amber-400" />
              </div>
            </div>
            <div>
              <h2 className="text-sm font-semibold text-neutral-100 tracking-tight">
                Compare &amp; Analyze Synthesis
              </h2>
              <p className="text-xs text-neutral-400">
                Cross-model evaluation across reasoning, accuracy, and depth
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            {analysis && (
              <button
                onClick={handleCopyReport}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-neutral-800 text-xs text-neutral-300 hover:bg-neutral-800 transition-colors"
                title="Copy entire analysis report"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copied ? 'Copied' : 'Copy Report'}</span>
              </button>
            )}
            <button
              onClick={onClose}
              className="p-1.5 rounded-lg text-neutral-400 hover:text-neutral-200 hover:bg-neutral-800 transition-colors"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Modal Body */}
        <div className="flex-1 overflow-y-auto p-6 space-y-6 text-sm text-neutral-300">
          {/* Privacy & Methodology Disclosure */}
          <div className="p-3.5 rounded-xl bg-neutral-900/60 border border-neutral-800 text-xs text-neutral-400 space-y-1">
            <div className="flex items-center gap-2 text-neutral-200 font-medium">
              <ShieldAlert className="w-4 h-4 text-cyan-400" />
              <span>Comparative Synthesis Disclosure</span>
            </div>
            <p className="leading-relaxed">
              This analysis is generated by Google Gemini using structured evaluative criteria.
              AI assessments are provided for research comparison and should not be treated as independently verified facts.
            </p>
          </div>

          {!analysis && !isLoading && (
            <div className="text-center py-12 space-y-4">
              <div className="w-12 h-12 mx-auto rounded-2xl bg-gradient-to-tr from-amber-500 to-rose-500 p-[1.5px] flex items-center justify-center">
                <div className="w-full h-full bg-neutral-950 rounded-[14px] flex items-center justify-center">
                  <Sparkles className="w-6 h-6 text-amber-400" />
                </div>
              </div>
              <div className="max-w-md mx-auto space-y-2">
                <h3 className="text-base font-semibold text-neutral-100">Ready to synthesize 4 model responses</h3>
                <p className="text-xs text-neutral-400 leading-relaxed">
                  Generate a deep breakdown identifying points of consensus, key disagreements, distinctive insights, and specific model strengths.
                </p>
              </div>
              <button
                onClick={onRunAnalysis}
                className="px-5 py-2.5 rounded-xl bg-neutral-100 text-neutral-950 font-semibold text-xs shadow hover:bg-white active:scale-95 transition-all"
              >
                Start Automated Analysis
              </button>
            </div>
          )}

          {isLoading && (
            <div className="text-center py-16 space-y-4">
              <div className="w-8 h-8 mx-auto rounded-full border-2 border-neutral-700 border-t-amber-400 animate-spin" />
              <p className="text-xs text-neutral-400 font-mono">Evaluating responses across all active frontier models...</p>
            </div>
          )}

          {analysis && (
            <div className="space-y-6 animate-fade-in">
              {/* Executive Summary */}
              <div className="p-4 rounded-xl bg-neutral-900/80 border border-neutral-800 space-y-2">
                <h3 className="text-xs font-semibold uppercase tracking-wider text-neutral-400 font-mono">
                  Executive Synthesis
                </h3>
                <p className="text-sm leading-relaxed text-neutral-200 font-sans">
                  {analysis.executiveSummary}
                </p>
              </div>

              {/* Trophies / Category Leaders */}
              <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
                <div className="p-3.5 rounded-xl bg-neutral-900/50 border border-neutral-800 space-y-1.5">
                  <div className="flex items-center gap-2 text-xs font-medium text-amber-400">
                    <Award className="w-4 h-4 shrink-0" />
                    <span>Best Explanation</span>
                  </div>
                  <div className="text-xs font-semibold text-neutral-100">
                    {PROVIDERS_CONFIG[analysis.bestExplanation.provider]?.name || analysis.bestExplanation.provider}
                  </div>
                  <p className="text-[11px] text-neutral-400 leading-relaxed">
                    {analysis.bestExplanation.rationale}
                  </p>
                </div>

                <div className="p-3.5 rounded-xl bg-neutral-900/50 border border-neutral-800 space-y-1.5">
                  <div className="flex items-center gap-2 text-xs font-medium text-cyan-400">
                    <Layers className="w-4 h-4 shrink-0" />
                    <span>Best Technical Response</span>
                  </div>
                  <div className="text-xs font-semibold text-neutral-100">
                    {PROVIDERS_CONFIG[analysis.bestTechnical.provider]?.name || analysis.bestTechnical.provider}
                  </div>
                  <p className="text-[11px] text-neutral-400 leading-relaxed">
                    {analysis.bestTechnical.rationale}
                  </p>
                </div>

                <div className="p-3.5 rounded-xl bg-neutral-900/50 border border-neutral-800 space-y-1.5">
                  <div className="flex items-center gap-2 text-xs font-medium text-rose-400">
                    <Sparkles className="w-4 h-4 shrink-0" />
                    <span>Strongest Reasoning</span>
                  </div>
                  <div className="text-xs font-semibold text-neutral-100">
                    {PROVIDERS_CONFIG[analysis.strongestReasoning.provider]?.name || analysis.strongestReasoning.provider}
                  </div>
                  <p className="text-[11px] text-neutral-400 leading-relaxed">
                    {analysis.strongestReasoning.rationale}
                  </p>
                </div>
              </div>

              {/* Consensus & Divergence Split */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                {/* Consensus */}
                <div className="p-4 rounded-xl bg-neutral-900/40 border border-neutral-800 space-y-3">
                  <div className="flex items-center gap-2 text-xs font-semibold text-emerald-400 font-mono uppercase tracking-wider">
                    <CheckCircle2 className="w-4 h-4" />
                    <span>Consensus / Shared Agreements</span>
                  </div>
                  <ul className="space-y-2 text-xs text-neutral-300">
                    {analysis.agreements.map((item, i) => (
                      <li key={i} className="flex items-start gap-2">
                        <span className="text-emerald-500 mt-0.5">•</span>
                        <span>{item}</span>
                      </li>
                    ))}
                  </ul>
                </div>

                {/* Divergence */}
                <div className="p-4 rounded-xl bg-neutral-900/40 border border-neutral-800 space-y-3">
                  <div className="flex items-center gap-2 text-xs font-semibold text-amber-400 font-mono uppercase tracking-wider">
                    <AlertTriangle className="w-4 h-4" />
                    <span>Divergences &amp; Disagreements</span>
                  </div>
                  <ul className="space-y-2 text-xs text-neutral-300">
                    {analysis.disagreements.map((item, i) => (
                      <li key={i} className="flex items-start gap-2">
                        <span className="text-amber-500 mt-0.5">•</span>
                        <span>{item}</span>
                      </li>
                    ))}
                  </ul>
                </div>
              </div>

              {/* Unique Insights per Model */}
              <div className="p-4 rounded-xl bg-neutral-900/40 border border-neutral-800 space-y-3">
                <div className="flex items-center gap-2 text-xs font-semibold text-purple-400 font-mono uppercase tracking-wider">
                  <Lightbulb className="w-4 h-4" />
                  <span>Unique Insights per Provider</span>
                </div>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-1">
                  {(['chatgpt', 'gemini', 'claude', 'grok'] as ProviderId[]).map((p) => {
                    const insights = analysis.uniqueInsights?.[p] || [];
                    const info = PROVIDERS_CONFIG[p];
                    if (insights.length === 0) return null;
                    return (
                      <div key={p} className="p-3 rounded-lg bg-neutral-950/60 border border-neutral-800/80 space-y-1.5">
                        <div className="flex items-center gap-2">
                          <span className="w-2 h-2 rounded-full" style={{ backgroundColor: info.accentColor }} />
                          <span className="text-xs font-semibold text-neutral-200">{info.name}</span>
                        </div>
                        <ul className="space-y-1 text-[11px] text-neutral-400">
                          {insights.map((ins, idx) => (
                            <li key={idx} className="flex items-start gap-1.5">
                              <span className="text-neutral-500">·</span>
                              <span>{ins}</span>
                            </li>
                          ))}
                        </ul>
                      </div>
                    );
                  })}
                </div>
              </div>

              {/* Contradictions / Warnings */}
              {analysis.factualContradictions && analysis.factualContradictions.length > 0 && (
                <div className="p-4 rounded-xl bg-rose-950/20 border border-rose-900/40 space-y-2">
                  <div className="flex items-center gap-2 text-xs font-semibold text-rose-400 font-mono uppercase tracking-wider">
                    <AlertTriangle className="w-4 h-4" />
                    <span>Contradictions &amp; Potential Inaccuracies</span>
                  </div>
                  <ul className="space-y-1.5 text-xs text-rose-200/90">
                    {analysis.factualContradictions.map((c, i) => (
                      <li key={i} className="flex items-start gap-2">
                        <span className="text-rose-400">•</span>
                        <span>{c}</span>
                      </li>
                    ))}
                  </ul>
                </div>
              )}
            </div>
          )}
        </div>

        {/* Modal Footer */}
        <div className="flex items-center justify-between px-6 py-3 border-t border-neutral-800 bg-neutral-900/60 select-none">
          <div className="text-[11px] text-neutral-500 font-mono">
            {analysis ? `Evaluated by ${analysis.evaluatedByModel}` : 'Awaiting analysis run'}
          </div>
          <button
            onClick={onClose}
            className="px-4 py-1.5 rounded-lg border border-neutral-700 bg-neutral-800 text-xs text-neutral-200 hover:bg-neutral-700 transition-colors"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
